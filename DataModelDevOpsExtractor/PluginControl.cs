        private async Task TryPopulateMarkdownTemplateFromPrimaryConnectionAsync()
        {
            if (Service == null)
            {
                return;
            }

            try
            {
                var markdownTemplate = await Task.Run(() => BuildMarkdownTemplateFromPrimaryConnectionLanguages(Service));
                if (string.IsNullOrWhiteSpace(markdownTemplate))
                {
                    return;
                }

                if (txtMarkdown.InvokeRequired)
                {
                    txtMarkdown.Invoke(new Action(() => ApplyGeneratedMarkdownTemplate(markdownTemplate)));
                }
                else
                {
                    ApplyGeneratedMarkdownTemplate(markdownTemplate);
                }
            }
            catch
            {
                // Non blocchiamo il caricamento del plugin se la retrieve lingue fallisce.
            }
        }

        private void ApplyGeneratedMarkdownTemplate(string markdownTemplate)
        {
            var current = txtMarkdown.Text ?? string.Empty;
            if (string.IsNullOrWhiteSpace(current) || (isMarkdownTemplateAutoGenerated && string.Equals(current, lastGeneratedMarkdownTemplate, StringComparison.Ordinal)))
            {
                txtMarkdown.Text = markdownTemplate;
                lastGeneratedMarkdownTemplate = markdownTemplate;
                isMarkdownTemplateAutoGenerated = true;
            }
        }

        private bool CanStartUploadWithCurrentMarkdown()
        {
            var current = NormalizeForComparison(txtMarkdown.Text);
            var autoTemplate = NormalizeForComparison(lastGeneratedMarkdownTemplate);

            var isDefaultAutoTemplate = !string.IsNullOrWhiteSpace(autoTemplate) &&
                string.Equals(current, autoTemplate, StringComparison.Ordinal);

            if (!isDefaultAutoTemplate)
            {
                return true;
            }

            MessageBox.Show(
                "Il markdown contiene ancora lo schema di default precompilato. Compila i dati reali oppure usa 'Load Markdown' prima di eseguire l'upload.",
                "Warning",
                MessageBoxButtons.OK,
                MessageBoxIcon.Warning);

            return false;
        }

        private static string NormalizeForComparison(string value)
        {
            return (value ?? string.Empty)
                .Replace("\r\n", "\n")
                .Replace("\r", "\n")
                .Trim();
        }

        private static string BuildMarkdownTemplateFromPrimaryConnectionLanguages(IOrganizationService service)
        {
            var headers = new List<string>
            {
                "System",
                "Table",
                "Schema name"
            };

            foreach (var languageCode in GetDisplayLanguageCodes(service))
            {
                headers.Add($"Display name ({languageCode})");
            }

            headers.Add("Description");
            headers.Add("Column type");
            headers.Add("Lookup table");
            headers.Add("Additional data");
            headers.Add("Requirement level");
            headers.Add("Primary");
            headers.Add("Usage");

            var separator = string.Join(" | ", headers.Select(_ => "---"));
            var emptyRow = string.Join(" | ", headers.Select(_ => string.Empty));

            return string.Join(Environment.NewLine, new[]
            {
                "## Table: <table_logical_name>",
                "Name EN : <table_display_name_en>",
                "Name IT : <table_display_name_it>",
                $"| {string.Join(" | ", headers)} |",
                $"| {separator} |",
                $"| {emptyRow} |"
            });
        }

        private static List<string> GetDisplayLanguageCodes(IOrganizationService service)
        {
            var fallback = new List<string> { "IT", "EN" };
            if (service == null)
            {
                return fallback;
            }

            var result = new List<string>();
            try
            {
                var response = (RetrieveAvailableLanguagesResponse)service.Execute(new RetrieveAvailableLanguagesRequest());
                var localeIds = response?.LocaleIds ?? new int[0];

                foreach (var localeId in localeIds.Where(id => id > 0).Distinct())
                {
                    try
                    {
                        var culture = CultureInfo.GetCultureInfo(localeId);
                        var code = (culture?.TwoLetterISOLanguageName ?? string.Empty).ToUpperInvariant();
                        if (!string.IsNullOrWhiteSpace(code) && !result.Contains(code, StringComparer.OrdinalIgnoreCase))
                        {
                            result.Add(code);
                        }
                    }
                    catch
                    {
                        // Ignora culture non risolvibili.
                    }
                }
            }
            catch
            {
                return fallback;
            }

            if (result.Count == 0)
            {
                return fallback;
            }

            if (!result.Contains("IT", StringComparer.OrdinalIgnoreCase))
            {
                result.Add("IT");
            }

            if (!result.Contains("EN", StringComparer.OrdinalIgnoreCase))
            {
                result.Add("EN");
            }

            return result;
        }

