        private async void buttonLoadMarkdown_Click(object sender, EventArgs e)
        {
            HideUploadProgressForOtherAction();
            HideUploadSummary();
            buttonLoadMarkdown.Enabled = false;
            try
            {
                var prefixEnv = NormalizePrefix(txtPrefix.Text);
                if (string.IsNullOrWhiteSpace(prefixEnv))
                {
                    MessageBox.Show("Prefix mancante. Inserisci il prefix e salva le configurazioni.");
                    return;
                }

                var dataModelService = new DataModelService();
                var markdown = await dataModelService.getDataModelMarkdown(
                    txtConnectionString.Text.Trim(),
                    prefixEnv,
                    txtTaskIds.Text.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries)
                );

                if (string.IsNullOrWhiteSpace(markdown))
                {
                    MessageBox.Show("Nessun contenuto trovato dai task indicati.");
                    return;
                }

                txtMarkdown.Text = markdown;
                isMarkdownTemplateAutoGenerated = false;
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Errore nel caricamento markdown: {ex.Message}");
            }
            finally
            {
                buttonLoadMarkdown.Enabled = true;
            }
        }

        private static string NormalizePrefix(string prefix)
        {
            var value = (prefix ?? string.Empty).Trim();
            if (string.IsNullOrWhiteSpace(value))
            {
                return string.Empty;
            }

            return value.EndsWith("_", StringComparison.Ordinal) ? value : value + "_";
        }

        private async void buttonCreateTask_Click(object sender, EventArgs e)
        {
            HideUploadProgressForOtherAction();
            HideUploadSummary();

            if (!CanStartUploadWithCurrentMarkdown())
            {
                return;
            }

            if (string.IsNullOrWhiteSpace(txtConnectionString.Text))
            {
                MessageBox.Show("Connection string DevOps mancante. Inseriscila prima di creare il task.");
                return;
            }

            if (!int.TryParse((txtParentTaskId.Text ?? string.Empty).Trim(), out var parentTaskId) || parentTaskId <= 0)
            {
                MessageBox.Show("Inserisci un Parent Task ID valido (numero intero positivo).");
                return;
            }

            var markdown = (txtMarkdown.Text ?? string.Empty).Trim();
            if (string.IsNullOrWhiteSpace(markdown))
            {
                MessageBox.Show("Markdown vuoto. Compila o carica il markdown prima di creare il task.");
                return;
            }

            buttonCreateTask.Enabled = false;
            try
            {
                var entityName = ExtractEntityNameFromMarkdown(markdown);
                var title = $"[D365] - Modifica DATA MODEL entita {entityName}";

                var repo = new DevOpsRepository(txtConnectionString.Text.Trim());
                var createdTask = await repo.CreateChildTaskAsync(parentTaskId, title, markdown);

                MessageBox.Show($"Task creato correttamente: ID {createdTask?.Id}");
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Errore nella creazione del task: {ex.Message}");
            }
            finally
            {
                buttonCreateTask.Enabled = true;
            }
        }

        private static string ExtractEntityNameFromMarkdown(string markdown)
        {
            if (string.IsNullOrWhiteSpace(markdown))
            {
                return "<entita>";
            }

            var tableHeaderMatch = Regex.Match(markdown, @"^\s*##\s*Table\s*:\s*(.+)$", RegexOptions.Multiline | RegexOptions.IgnoreCase);
            if (tableHeaderMatch.Success)
            {
                var tableName = tableHeaderMatch.Groups[1].Value.Trim();
                if (!string.IsNullOrWhiteSpace(tableName))
                {
                    return tableName;
                }
            }

            var tableRowMatch = Regex.Match(markdown, @"^\|\s*[^|]+\|\s*([^|]+)\|", RegexOptions.Multiline);
            if (tableRowMatch.Success)
            {
                var tableName = tableRowMatch.Groups[1].Value.Trim();
                if (!string.IsNullOrWhiteSpace(tableName) && !string.Equals(tableName, "Table", StringComparison.OrdinalIgnoreCase))
                {
                    return tableName;
                }
            }

            return "<entita>";
        }

